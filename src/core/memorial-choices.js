export function memorialChoices(template,province,state=null,fromId=null){
 const rows=template.choices||(template.relief?RELIEF:MEMORIAL_CHOICES[template.id]);
 if(!rows)throw new Error('此奏折缺少处置方案：'+template.id);
 const author=state?.court.officials.find(o=>o.id===fromId&&o.alive);
 const activeWar=state?.campaigns.find(w=>!w.done);
 const border=state?.nation.army.frontiers.find(b=>b.dir===activeWar?.dir)||state?.nation.army.frontiers.reduce((a,b)=>!a||b.threat>a.threat?b:a,null);
 const foreign=state?.foreign.find(f=>f.status!=='交战');
 return [...rows.map(([label,consequence,spec],i)=>{
  const {localMorale,localDisaster,readiness,threat,favor,attitude,...effects}=spec;
  if(localMorale!==undefined||localDisaster!==undefined)effects.province={id:province.id,...(localMorale!==undefined?{morale:localMorale}:{}),...(localDisaster!==undefined?{disaster:localDisaster}:{})};
  if(readiness!==undefined||threat!==undefined)effects.army={id:border?.dir||'capital',...(readiness!==undefined?{readiness}:{}),...(threat!==undefined&&border?{threat}:{})};
  if(favor!==undefined&&author)effects.official={id:author.id,favor};
  if(attitude!==undefined&&foreign)effects.foreign={id:foreign.id,attitude};
  return {id:['approve','reject','alternative'][i],label,consequence,effects};
 }),{id:'hold',label:'留中',effects:{}}];
}
